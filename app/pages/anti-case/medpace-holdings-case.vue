    <h4>What is narrative misalignment in investor relations?</h4>
    <div class="anti-prose">
      Narrative misalignment occurs when a company's public communications —
      earnings guidance, press releases, investor presentations — diverge from
      what analysts, journalists, and investors can independently verify. It is
      distinct from fraud or deliberate misrepresentation: most cases involve
      technically accurate statements that are framed in ways the market reads
      as evasive or optimistic relative to reality. For pre-profitability
      companies in deep tech, clean energy, or biotech, the tolerance for this
      kind of ambiguity is essentially zero.
